//  選択肢は [ラベル, ひとこと, 結果] で、結果は
//   { fx, text }                         … 必ずこうなる
//   { p, ok: {fx, text}, ng: {fx, text} } … 成功率 p で分かれる（p は能力で変わる）
// ===============================================================
const age = (s) => 18 + Math.floor(s.q / 4);
const g = (s) => s.unit.type === 'combi' || s.unit.type === 'trio';
const sk = (s, k) => (k === 'fame' ? s.fame / 10 : s.stats[k] ?? 50) / 100;

function SP(id, when, title, text, choices) {
  return {
    id, when, title,
    text: typeof text === 'function' ? text : () => text,
    choices: choices.map(([label, note, res]) => ({
      label, note,
      run: (s, h) => {
        let r = res;
        if (res.p) r = h.chance(typeof res.p === 'function' ? res.p(s) : res.p) ? res.ok : res.ng;
        h.add(r.fx || {});
        if (r.after) r.after(s, h);
        return typeof r.text === 'function' ? r.text(s, h) : r.text;
      },
    })),
  };
}

