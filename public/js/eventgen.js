// テンプレートごとのバリエーション数（テストで1000以上を確認）
export function countVariants() {
  return TEMPLATES.reduce((n, t) => n + t.list.length, 0);
}

// ---------------------------------------------------------------
//  文字列の差し込み
// ---------------------------------------------------------------
export function fill(str, v, s) {
  if (typeof str === 'function') return str(v, s);
  return String(str).replace(/\{(\w+)\}/g, (_, k) => {
    if (k === 'v') return typeof v === 'object' ? (v.name || v.title || v.n || '') : v;
    if (k === 'pet') return s?.family?.pets?.[0]?.name || 'ペット';
    return v && typeof v === 'object' && k in v ? v[k] : `{${k}}`;
  });
}
